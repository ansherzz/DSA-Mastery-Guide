import java.util.*;

/*
Problem: Find the Difference
Pattern: 02. Hashing
Difficulty: Easy

Interview Prompt:
You are given two strings s and t.
    String t is generated by randomly shuffling s and then adding one more letter at a random position.
    Return the letter that was added to t.

Why this pattern fits:
The two strings differ by exactly one unit in exactly one character's frequency.
    A frequency table exposes that difference directly.

Approach:
Count every character of s in a 26-slot table.
    Scan t and consume one count per character.
    The first character whose count would drop below zero is the extra letter.

Worked Example:
Example:
    s = "abcd", t = "abcde"
    After counting s, the letters a, b, c, d each have count 1. Scanning t, 'e' has no count left. Answer: e.

Time Complexity: O(n)
Space Complexity: O(1), a fixed 26-slot table
*/

public class P13_FindTheDifferenceHashing {
    public static char findTheDifference(String s, String t) {
        int[] counts = new int[26];
        for (char ch : s.toCharArray()) {
            counts[ch - 'a']++;
        }

        for (char ch : t.toCharArray()) {
            if (--counts[ch - 'a'] < 0) {
                return ch;
            }
        }
        throw new IllegalArgumentException("t has no extra letter");
    }

    public static void main(String[] args) {
        System.out.println(findTheDifference("abcd", "abcde"));
        System.out.println(findTheDifference("", "y"));
        System.out.println(findTheDifference("aabb", "ababa"));
    }
}
